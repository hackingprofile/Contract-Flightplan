use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::approve::approve;
use crate::error::{Error, Result};
use crate::verify::{verify_paths, VerifyReport};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CorpusReport {
    pub schema_version: String,
    pub kind: String,
    /// The u64 seed given to the fixture generator for every pack.
    pub seed: u64,
    pub packs: Vec<CorpusPack>,
    /// One row per mapping operation: verified outcomes of every catalogued
    /// fixture whose rules use it, and the required outcome kinds still missing.
    pub coverage: Vec<CoverageRow>,
    pub stable: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct CoverageRow {
    pub operation: String,
    pub counts: BTreeMap<String, usize>,
    /// Each requirement is met by any one of its outcome kinds.
    pub required: Vec<Vec<String>>,
    pub missing: Vec<String>,
}

/// The outcome kinds each operation must have at least one verified fixture
/// for: the refusals its implementation can reach from a well-typed, approved
/// rule. A null input counts as refused either by the operation
/// (`explicit_null`) or, when the source schema forbids null, by the schema.
pub fn required_outcomes(operation: &str) -> Vec<Vec<&'static str>> {
    let null = vec!["explicit_null", "schema_validation"];
    let mut required = vec![vec!["success"]];
    let more: &[&str] = match operation {
        "rename" | "copy" => &["missing", "collision"],
        "default" => &["null"],
        "drop" => &["missing"],
        "required_field" => &["missing", "null"],
        "enum_map" => &["missing", "null", "unknown_enum"],
        "safe_cast" | "unit_conversion" => &["missing", "null", "malformed"],
        "split" | "merge" | "pagination" => &["missing", "null", "malformed", "collision"],
        "array_map" => &["missing", "null", "malformed", "unknown_enum", "bound"],
        "array_filter" => &["missing", "null", "malformed", "bound"],
        _ => &[],
    };
    for kind in more {
        required.push(if *kind == "null" {
            null.clone()
        } else {
            vec![*kind]
        });
    }
    required
}

/// The 13 mapping operations, in the order the docs list them.
pub const OPERATIONS: [&str; 13] = [
    "rename",
    "copy",
    "default",
    "enum_map",
    "drop",
    "required_field",
    "safe_cast",
    "unit_conversion",
    "split",
    "merge",
    "array_map",
    "array_filter",
    "pagination",
];

/// Outcome-kind columns of the Markdown matrix, in a fixed order; kinds seen
/// outside this list are appended in sorted order.
const KINDS: [&str; 8] = [
    "success",
    "missing",
    "explicit_null",
    "schema_validation",
    "malformed",
    "collision",
    "unknown_enum",
    "bound",
];

fn coverage_rows(counts: &BTreeMap<String, BTreeMap<String, usize>>) -> Vec<CoverageRow> {
    OPERATIONS
        .iter()
        .map(|op| {
            let row_counts = counts.get(*op).cloned().unwrap_or_default();
            let required: Vec<Vec<String>> = required_outcomes(op)
                .into_iter()
                .map(|alts| alts.into_iter().map(str::to_string).collect())
                .collect();
            let missing = required
                .iter()
                .filter(|alts| {
                    !alts
                        .iter()
                        .any(|k| row_counts.get(k).copied().unwrap_or(0) > 0)
                })
                .map(|alts| alts.join(" or "))
                .collect();
            CoverageRow {
                operation: op.to_string(),
                counts: row_counts,
                required,
                missing,
            }
        })
        .collect()
}

/// The coverage matrix as Markdown, ready to check in.
pub fn render_matrix(report: &CorpusReport) -> String {
    let mut kinds: Vec<String> = KINDS.iter().map(|k| k.to_string()).collect();
    for row in &report.coverage {
        for kind in row.counts.keys() {
            if !kinds.contains(kind) {
                kinds.push(kind.clone());
            }
        }
    }
    kinds[KINDS.len()..].sort();
    let mut out = String::from(
        "# Coverage matrix\n\nGenerated by `cfp corpus --packs packs --matrix docs/COVERAGE-MATRIX.md`; `tests/coverage.rs` checks that this file matches a fresh run. Each cell counts catalogued fixtures whose rules use the operation and whose verified outcome is that kind. `Required` lists the outcome kinds each operation must have at least one fixture for (alternatives joined by \"or\"); `Status` is `met` or names what is missing.\n\n",
    );
    out.push_str("| Operation |");
    for kind in &kinds {
        out.push_str(&format!(" {kind} |"));
    }
    out.push_str(" Required | Status |\n|");
    for _ in 0..kinds.len() + 3 {
        out.push_str(" --- |");
    }
    out.push('\n');
    for row in &report.coverage {
        out.push_str(&format!("| {} |", row.operation));
        for kind in &kinds {
            out.push_str(&format!(
                " {} |",
                row.counts.get(kind).copied().unwrap_or(0)
            ));
        }
        let required: Vec<String> = row.required.iter().map(|alts| alts.join(" or ")).collect();
        let status = if row.missing.is_empty() {
            "met".to_string()
        } else {
            format!("MISSING: {}", row.missing.join(", "))
        };
        out.push_str(&format!(" {} | {status} |\n", required.join(", ")));
    }
    out.push_str(&format!(
        "\nPacks: {}. Catalogued fixtures: {}.\n",
        report.packs.len(),
        report
            .packs
            .iter()
            .map(|p| p.fixtures_catalogued)
            .sum::<usize>()
    ));
    out
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CorpusPack {
    pub name: String,
    pub passed: bool,
    pub fixtures: usize,
    /// Catalog items (`fixtures` counts every file under the fixtures folder).
    #[serde(default)]
    pub fixtures_catalogued: usize,
    /// Fixtures the seeded generator drew for the bodies the pack's rules
    /// read; every positive one must validate against its schema.
    pub generated: usize,
    /// Canonical digest of those generated fixtures: equal for equal seeds.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub generated_digest: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub message: Option<String>,
}

/// Run the corpus in a new, uniquely named folder under the system temporary
/// folder, and remove that folder afterwards whether the run passed or failed.
pub fn run_corpus_in_temp(packs_dir: &Path, seed: u64) -> Result<CorpusReport> {
    static NEXT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    let work = std::env::temp_dir().join(format!(
        "cfp-corpus-{}-{nanos}-{}",
        std::process::id(),
        NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
    ));
    // create_dir, not create_dir_all: an existing folder of that name is never reused.
    fs::create_dir(&work).map_err(|e| Error::io(work.display().to_string(), e))?;
    let report = run_corpus(packs_dir, &work, seed);
    let removed = fs::remove_dir_all(&work);
    let report = report?;
    removed.map_err(|e| Error::io(work.display().to_string(), e))?;
    Ok(report)
}

pub fn run_corpus(packs_dir: &Path, work_dir: &Path, seed: u64) -> Result<CorpusReport> {
    let mut packs = Vec::new();
    let mut stable = true;
    let mut counts: BTreeMap<String, BTreeMap<String, usize>> = BTreeMap::new();
    let entries =
        fs::read_dir(packs_dir).map_err(|e| Error::io(packs_dir.display().to_string(), e))?;
    let mut names = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|e| Error::io(packs_dir.display().to_string(), e))?;
        if entry.file_type().map(|ft| ft.is_dir()).unwrap_or(false) {
            names.push(entry.file_name().to_string_lossy().into_owned());
        }
    }
    names.sort();
    for name in names {
        let pack = packs_dir.join(&name);
        let outcome = run_pack(&name, &pack, work_dir)
            .and_then(|(report, count)| Ok((report, count, seeded_probe(&pack, seed)?)));
        match outcome {
            Ok((report, count, (generated, digest))) => {
                let catalogued = tally_outcomes(&pack, &report, &mut counts)?;
                packs.push(CorpusPack {
                    name,
                    passed: report.stable,
                    fixtures: count,
                    fixtures_catalogued: catalogued,
                    generated,
                    generated_digest: Some(digest),
                    message: None,
                });
                stable &= report.stable;
            }
            Err(err) => {
                stable = false;
                packs.push(CorpusPack {
                    name,
                    passed: false,
                    fixtures: 0,
                    fixtures_catalogued: 0,
                    generated: 0,
                    generated_digest: None,
                    message: Some(err.to_string()),
                });
            }
        }
    }
    let coverage = coverage_rows(&counts);
    stable &= coverage.iter().all(|row| row.missing.is_empty());
    Ok(CorpusReport {
        schema_version: "1".into(),
        kind: "corpus".into(),
        seed,
        packs,
        coverage,
        stable,
    })
}

/// Count each verified outcome once per operation its rules use.
fn tally_outcomes(
    pack: &Path,
    report: &VerifyReport,
    counts: &mut BTreeMap<String, BTreeMap<String, usize>>,
) -> Result<usize> {
    let proposal = crate::proposal::load_proposal(&pack.join("proposal.json"))?;
    let catalog = crate::verify::load_catalog(&pack.join("fixtures").join("catalog.json"))?;
    for outcome in &report.outcomes {
        let Some(item) = catalog.items.iter().find(|i| i.id == outcome.id) else {
            continue;
        };
        let mut ops: Vec<&str> = proposal
            .rules
            .iter()
            .filter(|r| item.rule_ids.contains(&r.id))
            .map(|r| r.operation.as_str())
            .collect();
        ops.sort();
        ops.dedup();
        for op in ops {
            *counts
                .entry(op.to_string())
                .or_default()
                .entry(outcome.actual.clone())
                .or_insert(0) += 1;
        }
    }
    Ok(catalog.items.len())
}

fn run_pack(name: &str, pack: &Path, work_dir: &Path) -> Result<(VerifyReport, usize)> {
    let source = pack.join("base.openapi.yaml");
    let dest = pack.join("next.openapi.yaml");
    let proposal = pack.join("proposal.json");
    let fixtures = pack.join("fixtures");
    let unique = work_dir.join(format!(
        "corpus-{name}-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos()
    ));
    fs::create_dir_all(&unique).map_err(|e| Error::io(unique.display().to_string(), e))?;
    let migration_path = unique.join("migration.json");
    let review_path = unique.join("review.json");
    let review = crate::verify::review_proposal(&proposal, &source, &dest)?;
    crate::approve::write_json(&review_path, &review)?;
    let migration = approve(
        &proposal,
        &source,
        &dest,
        &fixtures,
        &review_path,
        "corpus",
        Some("corpus runner"),
        Some("2026-09-18T00:00:00Z"),
    )?;
    crate::approve::write_json(&migration_path, &migration)?;
    let report = verify_paths(&migration_path, &proposal, &source, &dest, &fixtures)?;
    Ok((report, migration.fixtures.len()))
}

/// Run the seeded fixture generator over every source body the pack's rules
/// read. Each generated positive must validate against its schema. Returns
/// the number of generated fixtures and their canonical digest.
fn seeded_probe(pack: &Path, seed: u64) -> Result<(usize, String)> {
    let proposal = crate::proposal::load_proposal(&pack.join("proposal.json"))?;
    let source = crate::parse::load_openapi(&pack.join("base.openapi.yaml"))?;
    let ops = crate::parse::operations(&source)?;
    let mut seen = Vec::new();
    let mut generated = Vec::new();
    for rule in &proposal.rules {
        let key = (
            rule.source.operation.method.clone(),
            rule.source.operation.path.clone(),
            rule.source.location.clone(),
            rule.source.response_status.clone(),
        );
        if seen.contains(&key) {
            continue;
        }
        seen.push(key);
        let schema = crate::verify::body_schema(&source, &ops, rule, true)?;
        let fixtures = crate::fixtures::generate_from_schema(&schema, seed);
        for item in &fixtures.items {
            if item.expect == "success" {
                crate::schema::validate_instance(&schema, &item.body, &item.id)?;
            }
        }
        generated.push(fixtures);
    }
    let count = generated.iter().map(|g| g.items.len()).sum();
    let value = serde_json::to_value(&generated).map_err(|e| Error::Invalid {
        message: e.to_string(),
    })?;
    Ok((count, crate::digest::canonical_digest(&value)?))
}

pub fn pack_dirs(root: &Path) -> Result<Vec<PathBuf>> {
    let mut dirs = Vec::new();
    for entry in fs::read_dir(root).map_err(|e| Error::io(root.display().to_string(), e))? {
        let entry = entry.map_err(|e| Error::io(root.display().to_string(), e))?;
        if entry.file_type().map(|ft| ft.is_dir()).unwrap_or(false) {
            dirs.push(entry.path());
        }
    }
    dirs.sort();
    Ok(dirs)
}
