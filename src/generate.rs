    #[test]
    fn witness_is_computed_from_execution() {
        let drop = lossiness_witness(&root().join("packs/drop-legacy-flag")).unwrap();
        assert!(drop.consistent, "{:?}", drop.rules);
        assert!(drop
            .rules
            .iter()
            .all(|r| r.observed_lossiness == vec!["dropped".to_string()]));
        assert!(drop
            .rules
            .iter()
            .any(|r| r.discarded_fields.contains(&"legacy".to_string())));

        let rename = lossiness_witness(&root().join("packs/rename-user-id")).unwrap();
        assert!(rename.consistent);
        assert!(rename.rules.iter().all(|r| r.observed_lossiness.is_empty()));

        let default = lossiness_witness(&root().join("packs/default-status")).unwrap();
        assert!(default.consistent, "{:?}", default.rules);
    }
